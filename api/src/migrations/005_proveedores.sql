-- Maestro de proveedores, común a la aplicación y aislado por cliente.
CREATE TABLE IF NOT EXISTS farmetrica.proveedores_maestro (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 cliente_slug text NOT NULL REFERENCES farmetrica.clientes(slug) ON DELETE CASCADE,
 codigo_origen text NOT NULL,
 nombre text NOT NULL,
 tipo text NOT NULL DEFAULT 'sin_clasificar'
   CHECK (tipo IN ('cooperativa','laboratorio','mayorista','otros','sin_clasificar')),
 activo boolean NOT NULL DEFAULT true,
 actualizado_en timestamptz NOT NULL DEFAULT now(),
 UNIQUE(cliente_slug,codigo_origen)
);
CREATE INDEX IF NOT EXISTS proveedores_maestro_cliente_tipo
 ON farmetrica.proveedores_maestro(cliente_slug,tipo);
