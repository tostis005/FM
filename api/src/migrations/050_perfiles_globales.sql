-- 050 · Perfiles globales (aditivo, preserva exactamente modulos/secciones historicos).
-- Los perfiles pertenecen a la plataforma, no a una farmacia ni a un cliente.
CREATE TABLE IF NOT EXISTS farmetrica.perfiles (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 clave text NOT NULL UNIQUE CHECK (clave ~ '^[a-z0-9][a-z0-9_-]{2,80}$'),
 nombre text NOT NULL CHECK (length(btrim(nombre)) BETWEEN 1 AND 120),
 rol_base text NOT NULL CHECK (rol_base IN ('administrador','gestor','farmacia','colaborador')),
 modulos text[] DEFAULT NULL,
 secciones text[] DEFAULT NULL,
 permisos jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(permisos)='object'),
 sistema boolean NOT NULL DEFAULT false,
 actualizado_en timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE farmetrica.usuario_clientes
 ADD COLUMN IF NOT EXISTS perfil_id bigint REFERENCES farmetrica.perfiles(id);
CREATE INDEX IF NOT EXISTS usuario_clientes_perfil_idx
 ON farmetrica.usuario_clientes(perfil_id);

-- Solo la primera ejecución prepara los perfiles modelo; ejecutar otra vez
-- nunca sobrescribe cambios que el administrador haya hecho en un perfil.
DO $profiles$
DECLARE
 base record;
 existing record;
 picked_id bigint;
 profile_modules text[];
 profile_sections text[];
 profile_actions jsonb;
 variant_key text;
 variant_label text;
BEGIN
 FOR base IN
  SELECT * FROM (VALUES
   ('superadministrador','Superadministrador','administrador'),
   ('administrador','Administrador','administrador'),
   ('gestor','Gestor','gestor'),
   ('farmacia','Personal de farmacia','farmacia'),
   ('colaborador','Colaborador','colaborador')
  ) AS b(clave,nombre,rol)
 LOOP
  profile_modules:=NULL;
  profile_sections:=NULL;
  IF base.clave='colaborador' THEN
   profile_modules:='{}'::text[];
   profile_sections:='{}'::text[];
  ELSIF base.clave='farmacia' THEN
   profile_modules:=ARRAY['promociones']::text[];
   profile_sections:=ARRAY['promociones','seguimiento-global']::text[];
  END IF;
  IF base.clave NOT IN ('superadministrador') THEN
   SELECT uc.modulos,uc.secciones INTO profile_modules,profile_sections
   FROM farmetrica.usuario_clientes uc
   LEFT JOIN public.acceso_cuentas ac ON ac.email=uc.email
   WHERE uc.rol=base.rol
   ORDER BY
    CASE WHEN base.clave='gestor' AND lower(coalesce(ac.nombre,'')) LIKE '%cristina%' THEN 0 ELSE 1 END,
    CASE WHEN base.clave='farmacia' AND cardinality(uc.secciones)=2 THEN 0 ELSE 1 END,
    uc.email,uc.cliente_slug
   LIMIT 1;
   IF NOT FOUND THEN
    IF base.clave='colaborador' THEN
     profile_modules:='{}'::text[]; profile_sections:='{}'::text[];
    ELSIF base.clave='farmacia' THEN
     profile_modules:=ARRAY['promociones']::text[];
     profile_sections:=ARRAY['promociones','seguimiento-global']::text[];
    ELSE
     profile_modules:=NULL; profile_sections:=NULL;
    END IF;
   END IF;
  END IF;
  SELECT coalesce(jsonb_object_agg(clave,
   to_jsonb(CASE WHEN base.rol IN ('administrador','gestor')
    THEN ARRAY['ver','crear','editar','eliminar','importar','exportar']
    ELSE ARRAY['ver','exportar'] END)),'{}'::jsonb)
  INTO profile_actions FROM farmetrica.modulos;
  INSERT INTO farmetrica.perfiles(clave,nombre,rol_base,modulos,secciones,permisos,sistema)
  VALUES(base.clave,base.nombre,base.rol,profile_modules,profile_sections,profile_actions,true)
  ON CONFLICT(clave) DO NOTHING;
 END LOOP;

 -- No unificar cuentas solo por rol si sus permisos históricos difieren:
 -- cada combinación exacta se convierte en un perfil global reutilizable.
 FOR existing IN
  SELECT email,cliente_slug,rol,modulos,secciones
  FROM farmetrica.usuario_clientes WHERE perfil_id IS NULL
  ORDER BY cliente_slug,email
 LOOP
  picked_id:=NULL;
  SELECT id INTO picked_id FROM farmetrica.perfiles
   WHERE clave<>'superadministrador' AND rol_base=existing.rol
    AND modulos IS NOT DISTINCT FROM existing.modulos
    AND secciones IS NOT DISTINCT FROM existing.secciones
   ORDER BY sistema DESC,id LIMIT 1;
  IF picked_id IS NULL THEN
   variant_key:='migrado-'||substr(md5(existing.rol||'|'||
    coalesce(array_to_string(existing.modulos,E'\\x1f'),'<heredado>')||'|'||
    coalesce(array_to_string(existing.secciones,E'\\x1f'),'<heredado>')),1,24);
   variant_label:=CASE existing.rol
    WHEN 'gestor' THEN 'Gestor'
    WHEN 'administrador' THEN 'Administrador'
    WHEN 'farmacia' THEN 'Personal de farmacia'
    ELSE 'Colaborador' END||' · Variante '||substr(variant_key,9,6);
   SELECT coalesce(jsonb_object_agg(clave,
    to_jsonb(CASE WHEN existing.rol IN ('administrador','gestor')
     THEN ARRAY['ver','crear','editar','eliminar','importar','exportar']
     ELSE ARRAY['ver','exportar'] END)),'{}'::jsonb)
    INTO profile_actions FROM farmetrica.modulos;
   INSERT INTO farmetrica.perfiles(clave,nombre,rol_base,modulos,secciones,permisos)
   VALUES(variant_key,variant_label,existing.rol,existing.modulos,existing.secciones,profile_actions)
   ON CONFLICT(clave) DO NOTHING;
   SELECT id INTO picked_id FROM farmetrica.perfiles WHERE clave=variant_key;
  END IF;
  UPDATE farmetrica.usuario_clientes SET perfil_id=picked_id
   WHERE email=existing.email AND cliente_slug=existing.cliente_slug AND perfil_id IS NULL;
 END LOOP;

 -- Superadministración sigue dependiendo de la tabla de autorización real.
 -- Etiquetamos explícitamente al propietario, sin elevar ninguna cuenta nueva.
 UPDATE farmetrica.usuario_clientes uc
 SET perfil_id=(SELECT id FROM farmetrica.perfiles WHERE clave='superadministrador')
 WHERE uc.email='jose.fraga@gmail.com'
  AND EXISTS(SELECT 1 FROM farmetrica.superadministradores s WHERE s.email=uc.email)
  AND uc.perfil_id IS DISTINCT FROM
   (SELECT id FROM farmetrica.perfiles WHERE clave='superadministrador');
END $profiles$;
