-- 007. Solicitudes de privacidad independientes de captación comercial.
CREATE TABLE IF NOT EXISTS farmetrica.solicitudes_privacidad (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre varchar(120) NOT NULL,
 email varchar(254) NOT NULL,
 tipo varchar(30) NOT NULL
  CHECK(tipo IN ('acceso','rectificacion','supresion','oposicion','limitacion','portabilidad','otro')),
 detalle varchar(1500),
 estado varchar(20) NOT NULL DEFAULT 'pendiente'
  CHECK(estado IN ('pendiente','en_tramite','atendida')),
 creado_en timestamptz NOT NULL DEFAULT now(),
 actualizado_en timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS solicitudes_privacidad_estado_fecha
 ON farmetrica.solicitudes_privacidad(estado,creado_en DESC);
