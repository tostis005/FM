-- 006: solicitudes comerciales públicas, separadas de los datos de clientes y farmacias.
CREATE TABLE IF NOT EXISTS farmetrica.solicitudes_demo (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(120) NOT NULL,
  email varchar(254) NOT NULL,
  telefono varchar(40),
  pais varchar(80) NOT NULL DEFAULT 'España',
  farmacias varchar(20) NOT NULL,
  programa varchar(80) NOT NULL,
  interes varchar(80) NOT NULL,
  mensaje varchar(1500),
  origen varchar(100) NOT NULL DEFAULT 'directo',
  consentimiento boolean NOT NULL CHECK(consentimiento),
  estado varchar(20) NOT NULL DEFAULT 'nueva'
    CHECK (estado IN ('nueva','contactada','cerrada')),
  creado_en timestamptz NOT NULL DEFAULT now(),
  actualizado_en timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS solicitudes_demo_estado_fecha
  ON farmetrica.solicitudes_demo (estado, creado_en DESC);
