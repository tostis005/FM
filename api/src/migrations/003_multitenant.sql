-- 003 · Núcleo SaaS multiempresa (aditivo; conserva todas las tablas y datos existentes).
-- IMPORTANTE: esta migración NO renombra farmatic. El cambio físico se hace con
-- 004_ampedia_cutover_MANUAL.sql después de comprobar dependencias y crear backup.
CREATE SCHEMA IF NOT EXISTS farmetrica;

CREATE TABLE IF NOT EXISTS farmetrica.clientes (
  slug text PRIMARY KEY CHECK (slug ~ '^[a-z][a-z0-9_]{1,62}$'),
  nombre text NOT NULL,
  esquema_datos text NOT NULL CHECK (esquema_datos ~ '^[a-z][a-z0-9_]{1,62}$'),
  activo boolean NOT NULL DEFAULT true,
  creado_en timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS farmetrica.modulos (
  clave text PRIMARY KEY,
  nombre text NOT NULL,
  descripcion text NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS farmetrica.cliente_modulos (
  cliente_slug text NOT NULL REFERENCES farmetrica.clientes(slug) ON DELETE CASCADE,
  modulo_clave text NOT NULL REFERENCES farmetrica.modulos(clave),
  habilitado boolean NOT NULL DEFAULT false,
  PRIMARY KEY(cliente_slug, modulo_clave)
);

CREATE TABLE IF NOT EXISTS farmetrica.superadministradores (
  email text PRIMARY KEY,
  creado_en timestamptz NOT NULL DEFAULT now()
);

-- Un correo puede pertenecer a múltiples clientes con distintos permisos.
CREATE TABLE IF NOT EXISTS farmetrica.usuario_clientes (
  email text NOT NULL,
  cliente_slug text NOT NULL REFERENCES farmetrica.clientes(slug) ON DELETE CASCADE,
  rol text NOT NULL CHECK (rol IN ('administrador','gestor','farmacia','colaborador')),
  farmacias integer[] NOT NULL DEFAULT '{}',
  activo boolean NOT NULL DEFAULT true,
  PRIMARY KEY(email, cliente_slug)
);
CREATE INDEX IF NOT EXISTS usuario_clientes_cliente ON farmetrica.usuario_clientes(cliente_slug, activo);

CREATE TABLE IF NOT EXISTS farmetrica.farmacias (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_slug text NOT NULL REFERENCES farmetrica.clientes(slug),
  nombre text NOT NULL,
  ciudad text NOT NULL DEFAULT '',
  activo boolean NOT NULL DEFAULT true,
  codigo_origen varchar(16) NOT NULL,
  host_origen varchar(255),
  bd_origen varchar(100) NOT NULL DEFAULT 'Farmatic',
  actualizado_en timestamptz NOT NULL DEFAULT now(),
  UNIQUE(cliente_slug, codigo_origen),
  UNIQUE(cliente_slug,id)
);

